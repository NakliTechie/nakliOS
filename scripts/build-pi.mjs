// build-pi.mjs — bundle Pi's Worker (scripts/pi/src/worker.mjs) into apps/pi/pi-worker.js.
//
//   npm ci --prefix scripts/pi && node scripts/build-pi.mjs
//
// The bundle carries pi-durable, pi-ai and chord at the versions pinned in scripts/pi/package.json
// (MIT; see apps/pi/LICENSE-pi), plus the rig modules from sys/rig. Its sha256 and size go to
// apps/pi/build.json so a stale bundle is visible in review.
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const require = createRequire(root + 'scripts/pi/package.json');
const esbuild = require('esbuild');
const pkg = JSON.parse(await readFile(root + 'scripts/pi/package.json', 'utf8'));
const outfile = root + 'apps/pi/pi-worker.js';

await esbuild.build({
  entryPoints: [root + 'scripts/pi/src/worker.mjs'],
  bundle: true, format: 'esm', platform: 'browser', target: 'es2022', minify: true,
  outfile, legalComments: 'eof', logLevel: 'warning',
  banner: { js: `// Pi for NakliOS — generated by scripts/build-pi.mjs; do not edit. ${Object.entries(pkg.dependencies).map(([n, v]) => `${n}@${v}`).join(' ')} (MIT)` },
});

const bytes = await readFile(outfile);
const build = { bytes: bytes.length, sha256: createHash('sha256').update(bytes).digest('hex'), packages: pkg.dependencies };
await writeFile(root + 'apps/pi/build.json', JSON.stringify(build, null, 2) + '\n');
console.log(`apps/pi/pi-worker.js: ${build.bytes} bytes, sha256 ${build.sha256.slice(0, 12)}`);
