// Recipe commands: install the film looks pack (L60), auto tone and white balance (L14), red eye (L38),
// frequency separation (P44) and the channels read (P45). The pixel maths lives in src/files/recipes.js.

import { makeLayer } from '../document.js';
import { colourInfo } from '../../vendor/tessella/src/raw.js';
import { wbGains, solveAsShot } from '../../vendor/tessella/src/model.js';
import { validate } from '../bus.js';
import * as P from '../select/paint.js';
import { alone } from '../files/layered.js';
import { LOOKS, lookCube, greyWorldGains, autoToneParams, redEyeMask, redEyeFix, freqHigh, channelGrey, maskGrey } from '../files/recipes.js';
import { needDoc, needLayer, fail, change, layerRow } from './util.js';

const b64 = (u8) => { let s = ''; for (let i = 0; i < u8.length; i += 0x8000) s += String.fromCharCode(...u8.subarray(i, i + 0x8000)); return btoa(s); };

export function register(bus, ctx) {
  const rd = () => { if (!ctx.renderer) fail('unsupported', 'this command needs the WebGPU engine, which did not start', 'get_state', 'get_capabilities'); return ctx.renderer; };
  const store = () => { const s = ctx.storage(); if (!s) fail('unsupported', 'no workspace storage; grant a folder or allow browser storage', 'use_ui_control', 'grant_folder'); return s; };

  // ---- L60: write the looks pack as .cube files under presets/looks/ (existing files are left alone) ----
  bus.register('looks.install', async (_a, { viewOnly }) => {
    viewOnly();
    const s = store(); const written = []; const kept = [];
    for (const L of LOOKS) {
      const path = `presets/looks/${L.id}.cube`;
      if (await s.exists(path)) { kept.push(path); continue; }
      await s.write(path, new TextEncoder().encode(lookCube(L)));
      written.push(path);
    }
    return { looks: LOOKS.map((L) => ({ name: L.name, path: `presets/looks/${L.id}.cube` })), written, kept, licence: 'generated by Atelier from its own formula (MIT); no third-party LUT' };
  });

  // ---- L14: auto white balance and auto tone, applied as one undoable change ----
  function rawLayer(id) {
    const l = needLayer(ctx, id ?? ctx.store.doc?.activeLayerId);
    if (l.kind !== 'raw' || l.localOf) fail('unsupported', 'auto develop works on a RAW layer', 'change_target', 'open_photo');
    return l;
  }
  // Renders the RAW layer alone with develop d; returns the 8-bit and float images (max edge 512).
  async function renderWith(doc, l, d) {
    const r = rd();
    const v = { ...doc, layers: [{ ...l, develop: d, parentId: undefined, visible: true, opacity: 1, blend: 'normal', mask: null }] };
    await r.sync(v);
    return r.image8(r.lodFor(doc, 512), null, null);
  }
  bus.register('develop.auto', async (a) => {
    const doc = needDoc(ctx); const l = rawLayer(a.layerId); const r = rd();
    const wantWb = a.whiteBalance !== false; const wantTone = a.tone !== false;
    if (!wantWb && !wantTone) fail('invalid', 'nothing to do: tone and whiteBalance are both false', 'fix_argument', 'auto_develop');
    const src = await r.sourceSize(l);
    const TONE = { exposure: 0, contrast: 0, highlights: 0, shadows: 0, whites: 0, blacks: 0 };
    const params = {}; const notes = [];
    try {
      let T = l.develop?.temperature ?? src.asShot?.temperature; let tint = l.develop?.tint ?? src.asShot?.tint;
      if (wantWb) {
        const ci = src.meta ? colourInfo(src.meta) : null;
        if (!ci?.camXyz || T == null) fail('unsupported', 'auto white balance needs the camera matrix, which this RAW lacks', 'fix_argument', 'set_develop');
        // two rounds: measure the cast at the current balance, solve, measure again
        for (let round = 0; round < 2; round++) {
          const im = await renderWith(doc, l, { ...l.develop, ...TONE, temperature: T, tint });
          const f = im.float.data; const sum = [0, 0, 0]; let n = 0;
          for (let p = 0; p < f.length / 4; p++) {
            const al = f[p * 4 + 3]; if (al <= 0) continue;
            const c = [f[p * 4] / al, f[p * 4 + 1] / al, f[p * 4 + 2] / al];
            const y = 0.2627 * c[0] + 0.678 * c[1] + 0.0593 * c[2];   // Rec. 2020 luminance
            if (y < 0.02 || y > 0.8) continue;   // skip deep shadows and near-clipped light
            sum[0] += c[0]; sum[1] += c[1]; sum[2] += c[2]; n++;
          }
          if (n < 100) { notes.push('too few mid-tone pixels to judge the white balance; left as it was'); break; }
          const gains = greyWorldGains(sum.map((v) => v / n), colourInfo(src.meta).camToRec2020, wbGains(ci.camXyz, T, tint));
          if (!gains) break;
          const s = solveAsShot(ci.camXyz, gains);
          if (!s) break;
          T = Math.round(Math.min(50000, Math.max(2000, s.temperature))); tint = Math.round(Math.min(150, Math.max(-150, s.tint)));
        }
        params.temperature = T; params.tint = tint;
      }
      if (wantTone) {
        const im = await renderWith(doc, l, { ...l.develop, ...TONE, ...(params.temperature ? { temperature: params.temperature, tint: params.tint } : {}) });
        const hist = new Array(256).fill(0); const d = im.data;
        for (let p = 0; p < d.length / 4; p++) if (d[p * 4 + 3]) hist[Math.round(0.2126 * d[p * 4] + 0.7152 * d[p * 4 + 1] + 0.0722 * d[p * 4 + 2])]++;
        Object.assign(params, autoToneParams(hist));
        // one refinement: contrast, whites and blacks move the mid-tones too, so render with every setting and
        // move exposure again by log2(eotf(0.42) / eotf(median))
        const im2 = await renderWith(doc, l, { ...l.develop, ...params });
        const h2 = new Array(256).fill(0); const d2 = im2.data;
        for (let p = 0; p < d2.length / 4; p++) if (d2[p * 4 + 3]) h2[Math.round(0.2126 * d2[p * 4] + 0.7152 * d2[p * 4 + 1] + 0.0722 * d2[p * 4 + 2])]++;
        const tot = h2.reduce((x, y) => x + y, 0); let acc = 0; let med = 128;
        for (let i = 0; i < 256; i++) { acc += h2[i]; if (acc >= tot / 2) { med = Math.max(1, i); break; } }
        const ev = (v) => (v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4);
        params.exposure = Math.round(Math.max(-5, Math.min(5, params.exposure + Math.log2(ev(0.42) / ev(med / 255)))) * 100) / 100;
      }
    } finally { await r.sync(ctx.store.doc); }
    const schema = bus.manifest.tools.find((t) => t.name === 'set_develop').inputSchema.properties.params;
    const bad = validate(schema, params);
    if (bad) fail('outcome_unknown', `auto develop produced an out-of-range ${bad.field}`, 'get_state', 'get_develop');
    await change(ctx, 'auto_develop', (d) => { const x = d.layers.find((y) => y.id === l.id); x.develop = { ...x.develop, ...params }; });
    return { layerId: l.id, applied: params, notes, method: 'grey world in camera space (white balance) and histogram targets (tone); Atelier formulas, not fitted to Lightroom' };
  });

  // ---- L38: red eye inside a box (or a click and radius) on a retouch layer ----
  bus.register('retouch.red-eye', async (a) => {
    const doc = needDoc(ctx); const r = rd();
    let box = a.rect;
    if (!box && a.point) { const rad = a.radius ?? 30; box = { x: a.point[0] - rad, y: a.point[1] - rad, w: 2 * rad, h: 2 * rad }; }
    if (!box) fail('invalid', 'pass rect {x, y, w, h} or point [x, y] with radius', 'fix_argument', 'fix_red_eye');
    const x0 = Math.max(0, Math.floor(box.x)); const y0 = Math.max(0, Math.floor(box.y));
    const x1 = Math.min(doc.width, Math.ceil(box.x + box.w)); const y1 = Math.min(doc.height, Math.ceil(box.y + box.h));
    const w = x1 - x0; const h = y1 - y0;
    if (w < 3 || h < 3) fail('invalid', 'the box is outside the document or too small', 'fix_argument', 'fix_red_eye');
    if (w * h > 1024 * 1024) fail('invalid', 'the box is larger than 1024 × 1024 pixels; draw it around one eye', 'fix_argument', 'fix_red_eye');
    const im = await r.image8(0, [x0, y0, x1, y1], null);
    const { mask, pixels } = redEyeMask(im.data, w, h);
    if (!pixels) fail('invalid', 'no red pupil found in the box', 'change_target', 'fix_red_eye');
    const buffer = r.newPixels(w, h, redEyeFix(im.data, mask, w, h));
    const layer = makeLayer('raster', { name: 'Red eye', buffer, width: w, height: h, matrix: [1, 0, 0, 1, x0, y0] });
    await change(ctx, 'fix_red_eye', (d) => { d.layers.push(layer); d.activeLayerId = layer.id; });
    return { layer: layerRow(layer), pixels, box: { x: x0, y: y0, w, h } };
  });

  // ---- P44: frequency separation: a group with low (blurred) and high (linear light) layers ----
  bus.register('retouch.frequency', async (a) => {
    const doc = needDoc(ctx); const r = rd();
    const l = needLayer(ctx, a.layerId);
    if (['group', 'adjustment'].includes(l.kind) || l.localOf) fail('unsupported', 'frequency separation splits a pixel layer', 'change_target', 'list_layers');
    const radius = a.radius ?? 4;
    if (doc.width * doc.height > 40e6) fail('unsupported', 'documents above 40 megapixels are not split yet', 'change_target', 'set_document');
    let im;
    try { await r.sync({ ...doc, layers: alone(doc, l) }); im = await r.image8(0, null, null); } finally { await r.sync(ctx.store.doc); }
    const n = doc.width * doc.height;
    const orig = new Uint8Array(im.data.buffer.slice(0));
    const low = orig.slice(); P.gaussianBlur(low, doc.width, doc.height, radius, null);
    const high = freqHigh(orig, low, n);
    const lowBuf = r.newPixels(doc.width, doc.height, low); const highBuf = r.newPixels(doc.width, doc.height, high);
    const group = makeLayer('group', { name: `Frequency separation · ${l.name}`, isolation: 'pass-through', ...(l.parentId ? { parentId: l.parentId } : {}) });
    const lowL = makeLayer('raster', { name: 'Low frequency (colour and tone)', buffer: lowBuf, width: doc.width, height: doc.height, parentId: group.id });
    const highL = makeLayer('raster', { name: 'High frequency (texture)', buffer: highBuf, width: doc.width, height: doc.height, blend: 'linear-light', parentId: group.id });
    await change(ctx, 'frequency_separation', (d) => {
      const i = d.layers.findIndex((x) => x.id === l.id);
      d.layers.splice(i + 1, 0, group, lowL, highL);
      d.activeLayerId = highL.id;
    });
    return { group: layerRow(group), low: layerRow(lowL), high: layerRow(highL), radius };
  });

  // ---- P45: channels: R, G, B and alpha of the composite, plus saved selections as alpha channels ----
  bus.register('query.channels', async (a) => {
    const doc = needDoc(ctx); const r = rd();
    const maxEdge = a.maxEdge ?? 160;
    const im = await r.resize(await r.image8(r.lodFor(doc, maxEdge), null, null), maxEdge);
    const n = im.width * im.height;
    const jpeg = async (data) => b64(await r.encode({ width: im.width, height: im.height, data }, 'image/jpeg', 0.85));
    const mean = (data) => { let s = 0; for (let p = 0; p < n; p++) s += data[p * 4]; return Math.round((s / n) * 100) / 100; };
    const only = a.channel ? [a.channel] : ['red', 'green', 'blue', 'alpha'];
    const channels = [];
    for (const [c, name] of [['red', 0], ['green', 1], ['blue', 2], ['alpha', 3]]) {
      if (!only.includes(c)) continue;
      const g = channelGrey(im.data, n, name);
      channels.push({ channel: c, mean: mean(g), ...(a.images === false ? {} : { mime: 'image/jpeg', base64: await jpeg(g) }) });
    }
    const alphaChannels = [];
    for (const [nm, ref] of Object.entries(doc.savedSelections || {})) {
      const id = typeof ref === 'string' ? ref : ref?.buffer; const data = id && r.bufferData(id);
      if (!data) continue;
      const small = new Uint8Array(n);
      for (let y = 0; y < im.height; y++) for (let x = 0; x < im.width; x++) small[y * im.width + x] = data[Math.min(doc.height - 1, Math.floor((y + 0.5) * doc.height / im.height)) * doc.width + Math.min(doc.width - 1, Math.floor((x + 0.5) * doc.width / im.width))];
      const g = maskGrey(small, n);
      alphaChannels.push({ name: nm, mean: mean(g), ...(a.images === false ? {} : { mime: 'image/jpeg', base64: await jpeg(g) }) });
    }
    return { width: im.width, height: im.height, channels, alphaChannels, note: 'alpha channels are saved selections: refine_selection save and load' };
  });
}
